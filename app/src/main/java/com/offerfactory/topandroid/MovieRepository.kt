    /**
     * Возвращает случайный фильм из списка.
     */
    fun getRandomMovie(): Movie {
        return movies.random()
    }
    
    /**
     * Возвращает случайный фильм, исключая фильм с указанным ID.
     * Полезно для кнопки "Другой фильм" — гарантирует, что не повторится тот же фильм.
     */
    fun getRandomMovieExcluding(excludeId: Int): Movie {
        val availableMovies = movies.filter { it.id != excludeId }
        return availableMovies.random()
    }
    
    /**
     * Находит фильм по ID.
     * Возвращает null, если фильм не найден.
     */
    fun findMovieById(id: Int): Movie? {
        return movies.find { it.id == id }
    }
